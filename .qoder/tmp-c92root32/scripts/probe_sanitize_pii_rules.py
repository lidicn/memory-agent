"""_sanitize_pii 旧规则 vs 新规则对照（旧规则直接内联，不依赖工作区代码，任何时候可复跑）。"""
import re

OLD = [
    (r"(1[3-9]\d)\d{4}(\d{4})", "****"),
    (r"([\w.]{2})[\w.]*@", "***@"),
    (r"(\d{6})\d{8}(\d{4})", "********"),
    (r"\d{7,}", "***"),
]
NEW = [
    (r"(?<!\d)1[3-9]\d[\s-]?\d{4}[\s-]?\d{4}(?!\d)", "****"),
    (r"[A-Za-z0-9._%+-]+@", "***@"),
    (r"(?<!\d)[1-9]\d{5}(?:19|20)\d{2}(?:0[1-9]|1[0-2])"
     r"(?:0[1-9]|[12]\d|3[01])\d{3}[\dXx](?!\d)", "********"),
    (r"\d{7,}", "***"),
]


def apply(rules, t):
    for pat, rep in rules:
        t = re.sub(pat, rep, t)
    return t


for s in ["身份证110101199001011234", "身份证11010119900101123X", "卡号6222021234567890123",
          "13812345678912345", "联系邮箱someone@mail.com", "a@x.com", "电话138-1234-5678",
          "手机13812345678 邮箱someone@mail.com"]:
    print(f"{s!r:42} 旧 -> {apply(OLD, s)!r:26} 新 -> {apply(NEW, s)!r}")
